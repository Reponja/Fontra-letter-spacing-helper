import type { FontProject } from "./types";
import { activeSource } from "./project";

export function currentTrackingPerMille(project: FontProject): number {
  const tracking = project.tracking;
  if (tracking.activePreset === "custom") {
    return tracking.customPerMille;
  }
  return tracking.presets.find((preset) => preset.id === tracking.activePreset)?.perMille ?? 0;
}

export function trackingUnits(project: FontProject, perMille = currentTrackingPerMille(project)): number {
  return (perMille / 1000) * project.unitsPerEm;
}

export function setTrackingPreset(project: FontProject, presetId: string): void {
  project.tracking.activePreset = presetId;
}

export function setCustomTracking(project: FontProject, perMille: number): void {
  project.tracking.activePreset = "custom";
  project.tracking.customPerMille = perMille;
}

export function uppercaseGlyphs(project: FontProject): string[] {
  return activeSource(project)
    .glyphs.filter(
      (glyph) => glyph.category === "Uppercase" || glyph.category === "Smallcaps"
    )
    .map((glyph) => glyph.name);
}

export function allSpacingGlyphs(project: FontProject): string[] {
  return activeSource(project)
    .glyphs.filter((glyph) => glyph.category !== "Mark" && glyph.category !== "Space")
    .map((glyph) => glyph.name);
}

function classBlock(name: string, glyphNames: string[]): string {
  const names = glyphNames.length ? glyphNames : ["A"];
  return `@${name} = [${names.join(" ")}];`;
}

export interface FeatureExportOptions {
  includeCapsSpacing?: boolean;
  includeTrackingKern?: boolean;
  trackingPerMille?: number;
  capsPerMille?: number;
  className?: string;
}

export function generateTrackingFeatures(
  project: FontProject,
  options: FeatureExportOptions = {}
): string {
  const tracking = options.trackingPerMille ?? currentTrackingPerMille(project);
  const caps = options.capsPerMille ?? project.tracking.capsPerMille;
  const includeCaps = options.includeCapsSpacing ?? project.tracking.applyCapsSpacing;
  const includeTracking = options.includeTrackingKern ?? tracking !== 0;
  const className = options.className ?? "FIT_All";
  const uppercase = uppercaseGlyphs(project);
  const all = allSpacingGlyphs(project);
  const lines: string[] = [];
  lines.push(`# Generated by Fit — Letter Spacing Lab`);
  lines.push(`# Tracking: ${tracking} units per 1000 em`);
  lines.push(`# Caps spacing: ${caps} units per 1000 em`);
  lines.push("");
  if (includeTracking || includeCaps) {
    lines.push(classBlock(className, all));
    if (includeCaps) {
      lines.push(classBlock("FIT_Uppercase", uppercase));
    }
    lines.push("");
  }
  if (includeTracking) {
    lines.push("feature kern {");
    lines.push(`  # Uniform tracking lookup. Place after the main kern lookup.`);
    lines.push(`  pos @${className} <0 0 ${Math.round(tracking)} 0>;`);
    lines.push("} kern;");
    lines.push("");
  }
  if (includeCaps) {
    lines.push("feature cpsp {");
    lines.push(`  pos @FIT_Uppercase @FIT_Uppercase <0 0 ${Math.round(caps)} 0>;`);
    lines.push("} cpsp;");
    lines.push("");
  }
  return lines.join("\n");
}

export function trackingCss(project: FontProject): string {
  const perMille = currentTrackingPerMille(project);
  return `/* Fit — Letter Spacing Lab tracking export */\n.letter-spacing {\n  letter-spacing: ${(perMille / 1000).toFixed(4)}em; /* ${perMille} units / 1000 em */\n}\n`;
}

export function trackingJson(project: FontProject): string {
  return JSON.stringify(
    {
      font: project.name,
      unitsPerEm: project.unitsPerEm,
      trackingPerMille: currentTrackingPerMille(project),
      capsPerMille: project.tracking.capsPerMille,
      presets: project.tracking.presets,
      css: `${(currentTrackingPerMille(project) / 1000).toFixed(4)}em`,
    },
    null,
    2
  );
}

export function trackingCsv(project: FontProject): string {
  const rows = ["preset,perMille,em,note"];
  for (const preset of project.tracking.presets) {
    rows.push(
      `${escapeCsv(preset.label)},${preset.perMille},${(preset.perMille / 1000).toFixed(4)},${escapeCsv(preset.note)}`
    );
  }
  return rows.join("\n");
}

function escapeCsv(value: string): string {
  return `"${value.replaceAll('"', '""')}"`;
}

/**
 * A simple optical-size tracking ramp. Values are intentionally conservative:
 * text sizes get little or no tracking, small sizes get a little more, display
 * sizes get tighter.
 */
export function trackingRamp(project: FontProject): Array<{ size: number; perMille: number }> {
  const sizes = [6, 8, 9, 10, 11, 12, 14, 16, 20, 24, 32, 48, 72, 96, 144, 200];
  return sizes.map((size) => {
    const factor =
      size <= 12
        ? 1 + (12 - size) * 0.08
        : size <= 24
          ? 0.7
          : size <= 48
            ? 0.3
            : size <= 96
              ? -0.2
              : -0.6;
    return { size, perMille: Math.round(8 * factor) };
  });
}

export function trackingAdvance(project: FontProject, fontUnitsPerEm = project.unitsPerEm): number {
  return (currentTrackingPerMille(project) / 1000) * fontUnitsPerEm;
}
